private void cargarVendedores(List<Vendedor> lista) {

    DefaultTableModel modelo =
            (DefaultTableModel) jTable1.getModel();

    modelo.setRowCount(0);

    for (Vendedor v : lista) {
        modelo.addRow(new Object[]{
            v.getIdVendedor(),
            v.getNombre(),
            v.getApellido(),
            v.getTelefono(),
            v.getCorreo(),
            v.getDireccion()
        });
    }
}
