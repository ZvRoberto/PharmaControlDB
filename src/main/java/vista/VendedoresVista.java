    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     try {

    boolean resultado = controller.crearVendedor(
            jTextField2.getText(),
            jTextField3.getText(),
            jTextField4.getText(),
            jTextField5.getText(),
            jTextField6.getText()
    );

    if (resultado) {
        JOptionPane.showMessageDialog(this, "Vendedor creado correctamente");
        limpiarCampos();
        cargarVendedores(controller.leerTodos());
    } else {
        JOptionPane.showMessageDialog(this, "No se pudo crear el vendedor");
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       try {

    int id = Integer.parseInt(jTextField1.getText());

    boolean resultado = controller.actualizarVendedor(
            id,
            jTextField2.getText(),
            jTextField3.getText(),
            jTextField4.getText(),
            jTextField5.getText(),
            jTextField6.getText()
    );

    if (resultado) {
        JOptionPane.showMessageDialog(this, "Vendedor actualizado correctamente");
        limpiarCampos();
        cargarVendedores(controller.leerTodos());
    } else {
        JOptionPane.showMessageDialog(this, "No se pudo actualizar");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Ingrese un ID válido");
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
       try {

    int id = Integer.parseInt(jTextField1.getText());

    int opcion = JOptionPane.showConfirmDialog(
            this,
            "¿Desea eliminar este vendedor?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION
    );

    if (opcion == JOptionPane.YES_OPTION) {

        if (controller.eliminarVendedor(id)) {
            JOptionPane.showMessageDialog(this, "Vendedor eliminado correctamente");
            limpiarCampos();
            cargarVendedores(controller.leerTodos());
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Ingrese un ID válido");
}
    }//GEN-LAST:event_jButton3ActionPerformed

